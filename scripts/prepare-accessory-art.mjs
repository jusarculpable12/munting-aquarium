import sharp from 'sharp';
import { mkdir, writeFile } from 'node:fs/promises';

// Extract atlas cells without recoloring, resampling or changing generated transparency.
const source = process.argv[2] ?? 'public/art/accessories-v2.png';
const ids = ['coin-bush','grass-tuft','mini-fern','spear-leaf','oval-stem','scalloped-leaf','ribbon-grass','lance-stem','lime-leaf','oval-vine','leaf-thicket','pink-stem','live-fern','shelter-cave','sponge-filter','power-filter','air-stone','heater','led-light','tank-lid','river-gravel'];
const {width,height,hasAlpha}=await sharp(source).metadata();
if(!width||!height||!hasAlpha)throw new Error('Expected transparent accessory atlas');
await mkdir('public/art/accessories-v2',{recursive:true});
// Hand-checked gutters: generation keeps the objects in order but slightly varies row spacing.
const rowCuts=[0,265,525,790,1055,1330,1660,height];
const manifest={};
for(const [index,id] of ids.entries()){
 const col=index%3,row=Math.floor(index/3);
 const left=Math.round(col*width/3),top=rowCuts[row];
 const w=Math.round((col+1)*width/3)-left,h=rowCuts[row+1]-top;
 const {data,info}=await sharp(source).extract({left,top,width:w,height:h}).ensureAlpha().raw().toBuffer({resolveWithObject:true});
 let x0=w,y0=h,x1=-1,y1=-1;
 for(let y=0;y<h;y++)for(let x=0;x<w;x++)if(data[(y*w+x)*info.channels+3]>32){x0=Math.min(x0,x);y0=Math.min(y0,y);x1=Math.max(x1,x);y1=Math.max(y1,y);}
 if(x1<x0)throw new Error(`Empty atlas cell: ${id}`);
 const padding=3;
 x0=Math.max(0,x0-padding);y0=Math.max(0,y0-padding);x1=Math.min(w-1,x1+padding);y1=Math.min(h-1,y1+padding);
 const crop={left:left+x0,top:top+y0,width:x1-x0+1,height:y1-y0+1};
 await sharp(source).extract(crop).png().toFile(`public/art/accessories-v2/${id}.png`);
 manifest[id]={width:crop.width,height:crop.height};
}
await writeFile('game/accessory-art.ts',`// Generated by scripts/prepare-accessory-art.mjs. Original alpha and pixels retained.\nexport const accessoryArt = ${JSON.stringify(manifest,null,2)} as const;\n`);
console.log(`Extracted ${ids.length} accessory sprites from ${width}×${height} atlas.`);
